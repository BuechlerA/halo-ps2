#!/usr/bin/env python3
"""Per-map tag inventory (Markdown). Output contains counts and sizes only, never tag data.

    python3 -I tools/halo2ps2/report.py assets/decompressed/{a10,a30}.map -o docs/reports/tag-inventory.md
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from halo2ps2 import tagindex  # noqa: E402
from halo2ps2.tagindex import BITMAP_FORMATS, BITMAP_TYPES  # noqa: E402


def mib(n: int) -> str:
    return f"{n / 2**20:.2f}"


def map_section(m: tagindex.CacheMap) -> list[str]:
    out = [f"## {m.name}", ""]
    groups = Counter(t.group for t in m.tags)
    out += [f"{m.tag_count} tags; model raw data: "
            f"{m.vertex_count} vertex / {m.index_count} index objects.", "",
            "| group | tags |", "|---|---:|"]
    out += [f"| `{g}` | {n} |" for g, n in sorted(groups.items(), key=lambda kv: (-kv[1], kv[0]))]

    bm = list(m.bitmaps())
    by_fmt: Counter = Counter()
    bytes_fmt: Counter = Counter()
    dims: Counter = Counter()
    for _t, w, h, _d, ty, fmt, _mips, size in bm:
        key = f"{BITMAP_TYPES.get(ty, ty)}/{BITMAP_FORMATS.get(fmt, f'fmt{fmt}')}"
        by_fmt[key] += 1
        bytes_fmt[key] += size
        dims[f"{w}x{h}"] += 1
    out += ["", f"### Bitmaps: {len(bm)} images, {mib(sum(b[7] for b in bm))} MiB pixel data", "",
            "| type/format | images | MiB |", "|---|---:|---:|"]
    out += [f"| {k} | {n} | {mib(bytes_fmt[k])} |" for k, n in sorted(by_fmt.items())]
    out += ["", "Top resolutions: " + ", ".join(f"{d} ×{n}" for d, n in dims.most_common(8)), ""]

    snd = list(m.sounds())
    fmts = Counter((s[1], s[2], s[3]) for s in snd)
    out += [f"### Sounds: {len(snd)} tags, {sum(s[4] for s in snd)} permutations, "
            f"{mib(sum(s[5] for s in snd))} MiB sample data", "",
            "| sample_rate enum | compression enum | encoding enum | tags |", "|---:|---:|---:|---:|"]
    out += [f"| {r} | {c} | {e} | {n} |" for (r, c, e), n in sorted(fmts.items())]

    nodes, usage = m.script_function_usage()
    top = sorted(usage.items(), key=lambda kv: -kv[1])[:12]
    out += ["", f"### Scripts: {nodes} syntax nodes, {len(usage)} distinct built-in function indices", "",
            "Most used (index×calls; names resolved in Phase 4): " +
            ", ".join(f"{i}×{n}" for i, n in top), ""]
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("maps", nargs="+", type=Path, help="decompressed .map files")
    ap.add_argument("-o", "--out", type=Path, required=True)
    args = ap.parse_args(argv)
    lines = ["# Tag inventory (campaign maps)", "",
             "Generated by `tools/halo2ps2/report.py`. Counts and sizes only; no game data.",
             "Enum columns are raw tag values (sound enums not yet named).", ""]
    for p in args.maps:
        lines += map_section(tagindex.load(p))
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

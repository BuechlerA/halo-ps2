#define FONT_COUNT (sizeof k_font / sizeof k_font[0])

static const uint8_t *glyph(int ch)
{
	unsigned i;
	if (ch >= 'a' && ch <= 'z') ch -= 32;
	for (i = 0; i < FONT_COUNT; i++) if (k_font[i].ch == ch) return k_font[i].row;
	return k_font[13].row;    /* '?' */
}

void text_build_atlas(uint8_t atlas[TEXT_ATLAS_W * TEXT_ATLAS_H])
{
	int code, x, y;
	memset(atlas, 0, TEXT_ATLAS_W * TEXT_ATLAS_H);
	for (code = 32; code < 128; code++) {
		const uint8_t *g = glyph(code);
		int cx = ((code - 32) % 16) * 8, cy = ((code - 32) / 16) * 8;
		for (y = 0; y < 7; y++)
			for (x = 0; x < 5; x++)
				if (g[y] & (0x10 >> x)) atlas[(cy + y) * TEXT_ATLAS_W + cx + x] = 1;
	}
}

void text_build_clut(uint32_t clut[256])
{
	memset(clut, 0, 256 * sizeof clut[0]);
	clut[1] = 0xFFu | 0xFFu << 8 | 0xFFu << 16 | 0x80u << 24;
}

void text_batch_clear(text_batch_t *b)
{
	b->nchars = 0;
}

void text_batch_print(text_batch_t *b, int x, int y, uint32_t rgb, const char *s)
{
	int cx = x;
	for (; *s; s++) {
		if (*s == '\n') { cx = x; y += TEXT_CELL_H; continue; }
		if (b->nchars >= TEXT_MAX_CHARS) return;
		if (*s != ' ') {
			b->c[b->nchars].x = (int16_t)cx; b->c[b->nchars].y = (int16_t)y;
			b->c[b->nchars].ch = (uint8_t)*s;
			b->c[b->nchars].r = (uint8_t)(rgb >> 16); b->c[b->nchars].g = (uint8_t)(rgb >> 8); b->c[b->nchars].b = (uint8_t)rgb;
			b->nchars++;
		}
		cx += TEXT_CELL_W;
	}
}

int text_batch_emit(const text_batch_t *b, chain_t *c, uint32_t atlas_block, uint32_t clut_block,
                    int screen_w, int screen_h)
{
	uint32_t n = b->nchars, i, payload;
	uint32_t *w;
	uint64_t *q;
	if (n == 0) return 0;
	payload = 1 + 4 + 1 + n * 6;                       /* state tag + 4 A+D, sprite tag, 2 vertices x 3 qw per char */
	w = chain_cnt(c, 1 + payload, 0);
	if (!w) return -1;
	w[0] = VIF_CODE(VIF_NOP, 0, 0); w[1] = VIF_CODE(VIF_NOP, 0, 0);
	w[2] = VIF_CODE(VIF_FLUSHA, 0, 0); w[3] = VIF_CODE(VIF_DIRECT, 0, payload);
	q = (uint64_t *)(w + 4);
	q[0] = GIF_TAG(4, 0, 0, 0, GIFX_FLG_PACKED, 1); q[1] = GIF_REGS_AD;
	q[2] = GS_TEX0(atlas_block, TEXT_ATLAS_W / 64, GS_PSMT8, 7, 6, 1, 0, clut_block, GS_PSMCT32, 0, 0, 1);
	q[3] = GS_A_TEX0_1;
	q[4] = GS_TEX1(1, 0, 0, 0, 0, 0, 0);               q[5] = GS_A_TEX1_1;          /* nearest, no mips */
	q[6] = GS_ALPHA(0, 1, 0, 1, 0);                    q[7] = GS_A_ALPHA_1;         /* (Cs - Cd) * As + Cd */
	q[8] = GS_TEST(0, 1, 0, 0, 0, 0, 1, 1);            q[9] = GS_A_TEST_1;          /* no alpha test, Z always */
	q[10] = GIF_TAG(n * 2, 1, 1, GS_PRIM(6, 0, 1, 0, 1, 0, 1, 0, 0), GIFX_FLG_PACKED, 3);
	q[11] = 0x531;                                     /* RGBAQ, UV, XYZ2 */
	q += 12;
	for (i = 0; i < n; i++) {
		int cell = b->c[i].ch - 32, k;
		int u0 = (cell % 16) * 8, v0 = (cell / 16) * 8;
		int x0 = b->c[i].x, y0 = b->c[i].y;
		(void)screen_h;
		for (k = 0; k < 2; k++) {
			int u = u0 + (k ? TEXT_CELL_W : 0), v = v0 + (k ? TEXT_CELL_H : 0);
			int x = x0 + (k ? TEXT_CELL_W : 0), y = y0 + (k ? TEXT_CELL_H : 0);
			/* RGBAQ packed: one byte per 32-bit lane. */
			q[0] = (uint64_t)b->c[i].r | (uint64_t)b->c[i].g << 32;
			q[1] = (uint64_t)b->c[i].b | (uint64_t)0x80 << 32;
			/* UV in 10.4 fixed point. */
			q[2] = (uint64_t)(u * 16) | (uint64_t)(v * 16) << 32;
			q[3] = 0;
			q[4] = (uint64_t)((2048 - screen_w / 2 + x) * 16) | (uint64_t)((2048 - screen_h / 2 + y) * 16) << 32;
			q[5] = 0xFFFFFFull;                                                  /* Z (low lane of the 2nd word) */
			q += 6;
		}
	}
	return c->overflow ? -1 : 0;
}

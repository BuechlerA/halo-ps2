#!/usr/bin/env bash
# Prepare xemu (original Xbox emulator) for parity checks against the PS2 port (docs/14-xbox-reference.md).
# Reads the user-supplied Xbox boot files, validates them, and writes a project-local xemu config to
# assets/xemu/xemu.toml (gitignored) so the user's global xemu settings are never touched. Nothing is copied or downloaded.
#
#   XBOX_BIOS_DIR  folder holding the files below      (default: ~/Developer/xbox-bios)
#   XBOX_MCPX      MCPX boot ROM, 512 bytes             (default: first mcpx*.bin in XBOX_BIOS_DIR)
#   XBOX_FLASH     flash BIOS, 256 KiB..1 MiB           (default: first other *.bin in XBOX_BIOS_DIR)
#   XBOX_HDD       formatted HDD image, qcow2           (default: first *.qcow2 in XBOX_BIOS_DIR)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
XEMU="${XEMU:-/Applications/xemu.app/Contents/MacOS/xemu}"
BIOS_DIR="${XBOX_BIOS_DIR:-$HOME/Developer/xbox-bios}"
STATE="$ROOT/assets/xemu"

die() { echo "xemu-setup: $*" >&2; exit 1; }
first() { # first <dir> <glob...>: first matching file, case-insensitive, or empty
  find "$1" -maxdepth 1 -type f \( "${@:2}" \) 2>/dev/null | sort | head -n 1
}
size() { stat -f %z "$1"; }

[ -x "$XEMU" ] || die "xemu not found at $XEMU (brew install --cask xemu, or set XEMU=)"

MCPX="${XBOX_MCPX:-}"
FLASH="${XBOX_FLASH:-}"
HDD="${XBOX_HDD:-}"
if [ -d "$BIOS_DIR" ]; then
  [ -n "$MCPX" ] || MCPX="$(first "$BIOS_DIR" -iname 'mcpx*.bin')"
  [ -n "$HDD" ] || HDD="$(first "$BIOS_DIR" -iname '*.qcow2')"
  [ -n "$FLASH" ] || FLASH="$(first "$BIOS_DIR" -iname '*.bin' ! -iname 'mcpx*' ! -iname 'eeprom*')"
fi

missing=0
for pair in "MCPX boot ROM (XBOX_MCPX):$MCPX" "flash BIOS (XBOX_FLASH):$FLASH" "HDD image (XBOX_HDD):$HDD"; do
  label="${pair%%:*}"; path="${pair#*:}"
  if [ -z "$path" ] || [ ! -f "$path" ]; then echo "missing: $label" >&2; missing=1; fi
done
[ "$missing" = 0 ] || die "put the files in $BIOS_DIR (or set the variables above); see docs/14-xbox-reference.md"

[ "$(size "$MCPX")" = 512 ] || die "MCPX boot ROM must be 512 bytes: $MCPX is $(size "$MCPX")"
case "$(size "$FLASH")" in 262144|524288|1048576) ;; *) die "flash BIOS must be 256 KiB, 512 KiB or 1 MiB: $FLASH is $(size "$FLASH")";; esac
qemu-img info "$HDD" >/dev/null 2>&1 || file "$HDD" | grep -q QCOW || die "HDD image is not a qcow2/raw disk image: $HDD"

mkdir -p "$STATE"
# EEPROM (serial, region, video standard) is created by xemu on first run if the file does not exist; keep it with the config.
cat > "$STATE/xemu.toml" <<EOF
# Generated by scripts/xemu-setup.sh - do not edit by hand, rerun the script.
[sys.files]
bootrom_path = '$MCPX'
flashrom_path = '$FLASH'
eeprom_path = '$STATE/eeprom.bin'
hdd_path = '$HDD'
EOF
echo "wrote $STATE/xemu.toml"
echo "  MCPX  $MCPX"
echo "  flash $FLASH"
echo "  HDD   $HDD"
echo "next: scripts/xemu-run.sh"
